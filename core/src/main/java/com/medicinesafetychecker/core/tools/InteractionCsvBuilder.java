package com.medicinesafetychecker.core.tools;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

import com.medicinesafetychecker.core.CsvLoader;
import com.medicinesafetychecker.core.Medicine;

/**
 * One-off data-prep tool: filters the full Kaggle drug-interactions CSV down
 * to only the pairs where both drugs are in our seed medicines
 * (data/seed/medicines.csv), and assigns a MAJOR/MODERATE/MINOR severity by
 * keyword-matching the interaction description. Writes data/seed/interactions.csv.
 *
 * <p>Run with the repository root as the working directory, e.g.
 * {@code java -cp core/target/classes com.medicinesafetychecker.core.tools.InteractionCsvBuilder}.
 */
public final class InteractionCsvBuilder {

    private static final Path DEFAULT_MEDICINES_CSV = Path.of("data/seed/medicines.csv");
    private static final Path DEFAULT_RAW_CSV = Path.of("data/raw/db_drug_interactions.csv");
    private static final Path DEFAULT_OUTPUT_CSV = Path.of("data/seed/interactions.csv");

    // The Kaggle dataset uses DrugBank's chemical names for a few of our medicines.
    private static final Map<String, String> DATASET_NAME_ALIASES = Map.of(
            "acetaminophen", "Paracetamol",
            "acetylsalicylic acid", "Aspirin",
            "candesartan cilexetil", "Candesartan"
    );

    // "hypotension" is deliberately NOT a MAJOR keyword: in this dataset it almost
    // always describes the expected, additive blood-pressure-lowering effect of
    // combining two antihypertensives (e.g. an ARB + a thiazide diuretic) - a
    // routine, often intentionally co-prescribed combination, not a severe one.
    // "qtc" and "arrhythm" are kept as word-root prefixes (rather than full words
    // like "qtc prolongation" or "arrhythmia") because this dataset phrases them
    // as "QTc-prolonging" and "arrhythmogenic" - a literal keyword match on the
    // textbook wording misses the actual descriptions and under-classifies real
    // QT-prolongation / arrhythmia risk combinations as MINOR.
    private static final String[] MAJOR_KEYWORDS = {
            "bleeding", "qtc", "arrhythm", "heart failure",
            "hyperkalemia", "respiratory depression", "serotonin syndrome",
            "seizure", "toxicity", "fatal", "life-threatening"
    };

    private static final String[] MODERATE_KEYWORDS = {
            "adverse effects", "hypersensitivity", "efficacy", "hypertension", "hypotension"
    };

    private InteractionCsvBuilder() {
    }

    public static void main(String[] args) throws IOException {
        Path rawCsv = args.length > 0 ? Path.of(args[0]) : DEFAULT_RAW_CSV;
        Path medicinesCsv = args.length > 1 ? Path.of(args[1]) : DEFAULT_MEDICINES_CSV;
        Path outputCsv = args.length > 2 ? Path.of(args[2]) : DEFAULT_OUTPUT_CSV;

        Map<String, String> canonicalNamesByLowerCase = loadCanonicalNames(medicinesCsv);
        int written = buildInteractionsCsv(rawCsv, outputCsv, canonicalNamesByLowerCase);

        System.out.println("Wrote " + written + " interactions to " + outputCsv);
    }

    /** Lower-cased dataset/alias name -> our canonical medicine name. */
    private static Map<String, String> loadCanonicalNames(Path medicinesCsv) throws IOException {
        Map<String, String> names = new HashMap<>();
        for (Medicine medicine : CsvLoader.loadMedicines(medicinesCsv)) {
            names.put(medicine.getName().toLowerCase(Locale.ROOT), medicine.getName());
        }
        DATASET_NAME_ALIASES.forEach(names::put);
        return names;
    }

    private static int buildInteractionsCsv(Path rawCsv, Path outputCsv, Map<String, String> canonicalNamesByLowerCase)
            throws IOException {
        int written = 0;
        Set<String> seenPairs = new HashSet<>();

        try (BufferedReader reader = Files.newBufferedReader(rawCsv);
             Writer writer = Files.newBufferedWriter(outputCsv)) {

            writer.write("# Generated by InteractionCsvBuilder from data/raw/db_drug_interactions.csv - demo subset only\n");
            writer.write("medicineNameA,medicineNameB,severity,description\n");

            reader.readLine(); // header line of the raw CSV, discarded
            String line;
            while ((line = reader.readLine()) != null) {
                String[] fields = CsvLoader.splitCsvLine(line);
                if (fields.length != 3) {
                    continue; // malformed row, skip it
                }

                String canonicalA = canonicalNamesByLowerCase.get(fields[0].strip().toLowerCase(Locale.ROOT));
                String canonicalB = canonicalNamesByLowerCase.get(fields[1].strip().toLowerCase(Locale.ROOT));
                if (canonicalA == null || canonicalB == null) {
                    continue; // one of the two drugs is not in our seed list
                }

                String pairKey = unorderedPairKey(canonicalA, canonicalB);
                if (!seenPairs.add(pairKey)) {
                    continue; // the raw dataset lists some pairs in both directions
                }

                String description = fields[2].strip();
                String severity = classifySeverity(description);

                writer.write(CsvLoader.escapeCsvField(canonicalA));
                writer.write(',');
                writer.write(CsvLoader.escapeCsvField(canonicalB));
                writer.write(',');
                writer.write(severity);
                writer.write(',');
                writer.write(CsvLoader.escapeCsvField(description));
                writer.write('\n');
                written++;
            }
        }
        return written;
    }

    private static String unorderedPairKey(String a, String b) {
        String lowerA = a.toLowerCase(Locale.ROOT);
        String lowerB = b.toLowerCase(Locale.ROOT);
        return lowerA.compareTo(lowerB) <= 0 ? lowerA + "|" + lowerB : lowerB + "|" + lowerA;
    }

    private static String classifySeverity(String description) {
        String lower = description.toLowerCase(Locale.ROOT);
        for (String keyword : MAJOR_KEYWORDS) {
            if (lower.contains(keyword)) {
                return "MAJOR";
            }
        }
        for (String keyword : MODERATE_KEYWORDS) {
            if (lower.contains(keyword)) {
                return "MODERATE";
            }
        }
        return "MINOR";
    }
}
